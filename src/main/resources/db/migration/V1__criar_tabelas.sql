-- Usuários (autenticação)
CREATE TABLE TB_USUARIO (
    ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME      VARCHAR2(120) NOT NULL,
    EMAIL     VARCHAR2(150) NOT NULL,
    SENHA     VARCHAR2(100) NOT NULL,
    PERFIL    VARCHAR2(10)  NOT NULL,
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL IN ('ADMIN', 'USER'))
);

-- Empresas monitoradas
CREATE TABLE TB_EMPRESA (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME       VARCHAR2(150) NOT NULL,
    CNPJ       VARCHAR2(14)  NOT NULL,
    SETOR      VARCHAR2(100),
    EMAIL      VARCHAR2(150),
    CRIADO_EM  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_EMPRESA_CNPJ UNIQUE (CNPJ)
);

-- Medições de consumo de energia
CREATE TABLE TB_MEDICAO (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPRESA_ID    NUMBER NOT NULL,
    DATA_MEDICAO  DATE NOT NULL,
    CONSUMO_KWH   NUMBER(14,2) NOT NULL,
    FONTE         VARCHAR2(20) NOT NULL,
    CUSTO         NUMBER(14,2),
    CONSTRAINT FK_MEDICAO_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES TB_EMPRESA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_MEDICAO_CONSUMO CHECK (CONSUMO_KWH > 0),
    CONSTRAINT CK_MEDICAO_FONTE CHECK (FONTE IN ('REDE','SOLAR','EOLICA','BIOMASSA','GERADOR_DIESEL'))
);
CREATE INDEX IDX_MEDICAO_EMPRESA_DATA ON TB_MEDICAO (EMPRESA_ID, DATA_MEDICAO);

-- Metas de consumo mensal
CREATE TABLE TB_META_CONSUMO (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPRESA_ID          NUMBER NOT NULL,
    LIMITE_MENSAL_KWH   NUMBER(14,2) NOT NULL,
    VIGENTE_DESDE       DATE NOT NULL,
    STATUS              VARCHAR2(10) DEFAULT 'ATIVA' NOT NULL,
    CONSTRAINT FK_META_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES TB_EMPRESA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_META_LIMITE CHECK (LIMITE_MENSAL_KWH > 0),
    CONSTRAINT CK_META_STATUS CHECK (STATUS IN ('ATIVA','INATIVA'))
);
CREATE INDEX IDX_META_EMPRESA_STATUS ON TB_META_CONSUMO (EMPRESA_ID, STATUS);

-- Alertas automáticos de consumo acima da meta
CREATE TABLE TB_ALERTA (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPRESA_ID    NUMBER NOT NULL,
    COMPETENCIA   VARCHAR2(7)  NOT NULL,
    CONSUMO_KWH   NUMBER(14,2) NOT NULL,
    LIMITE_KWH    NUMBER(14,2) NOT NULL,
    MENSAGEM      VARCHAR2(300) NOT NULL,
    STATUS        VARCHAR2(10) DEFAULT 'ABERTO' NOT NULL,
    CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RESOLVIDO_EM  TIMESTAMP,
    CONSTRAINT FK_ALERTA_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES TB_EMPRESA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_ALERTA_STATUS CHECK (STATUS IN ('ABERTO','RESOLVIDO'))
);
CREATE INDEX IDX_ALERTA_EMPRESA_STATUS ON TB_ALERTA (EMPRESA_ID, STATUS);
